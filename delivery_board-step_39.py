def print_usage_scenarios():
    """Демонстрирует основные сценарии использования DeliveryBoard.

    Сценарии:
    1. Создание заказа и назначение курьера.
    2. Обновление статуса заказа и отслеживание его прогресса.
    3. Расчет стоимости доставки в зависимости от расстояния.
    4. Визуализация маршрута курьера с помощью текстового отчета.
    5. Управление статусами курьера и назначение на новые заказы.
    """
    print("=== Сценарий 1: Создание заказа и назначение курьера ===")
    order = create_order("Москва", "ул. Ленина 10", "Срочно", 500)
    courier = create_courier("Иван Иванов", "Москва", "ул. Ленина 10", "Срочно", 500)
    assign_courier_to_order(order, courier)
    print(f"Заказ: {order['id']}, Курьер: {courier['id']}, Статус: {order['status']}")

    print("\n=== Сценарий 2: Обновление статуса заказа ===")
    update_order_status(order, "Доставлено")
    print(f"Статус заказа: {order['status']}")

    print("\n=== Сценарий 3: Расчет стоимости доставки ===")
    cost = calculate_delivery_cost(order['distance'])
    print(f"Стоимость доставки: {cost} руб.")

    print("\n=== Сценарий 4: Визуализация маршрута курьера ===")
    route_visualization(courier['route'], order['destination'])
    print("Маршрут курьера визуализирован.")

    print("\n=== Сценарий 5: Управление статусами курьера ===")
    update_courier_status(courier, "Свободен")
    print(f"Статус курьера: {courier['status']}")
